"""Cell-level analysis of the CNN readings on test_final (read-only, from existing runs).

    python scripts/analyse_cells.py

Uses the PR #9 logit dump (outputs/e2e/cell_logits_test_final.npz, aligned with the run CSVs by
scripts/check_unweighted.py: 1599 images, every per-image misread count equal to the CSV). The
argmax of the logits is the CNN reading every method saw (temperature does not change it).

Writes:
  report/results/confusions.csv / confusions.md   (true -> read) pairs: overall, per noise type,
                                                    per font (Item 2 of the verification pass)
  report/results/noise_flips.csv / noise_flips.md each noisy image vs the clean render of the same
                                                    puzzle: cells wrong->right and right->wrong
  report/figures/fig8_confusions.{png,pdf}
"""

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))
from check_unweighted import LOGITS, MAIN, RENDERS, load_cells  # noqa: E402
from make_report import INK, parse_set, save, style_axes  # noqa: E402

RES = Path("report/results")
NOISE_ORDER = ["clean", "blur", "gaussian_noise", "jpeg", "lighting", "rotate"]


def short(font: str) -> str:
    return font.split("[")[0].split("-")[0].replace(".ttf", "")


def load():
    ids, lg, t = load_cells()
    labels = np.load(LOGITS)["labels"].astype(int).reshape(-1, 81)
    pred = lg.argmax(2)
    fonts = [
        short(json.loads((RENDERS / s / f"{im}.json").read_text("utf-8"))["font"]) for s, im in ids
    ]
    from check_unweighted import prob_grid

    probs = np.stack([prob_grid(z, t).reshape(81, 10) for z in lg])
    return ids, labels, pred, fonts, probs


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def pair(t, p):
    return f"{'empty' if t == 0 else t} -> {'empty' if p == 0 else p}"


def confusions(ids, labels, pred, fonts):
    by = defaultdict(Counter)  # (noise, severity, font) -> Counter[(t, p)]
    for (s, _), lab, pr, f in zip(ids, labels, pred, fonts, strict=True):
        kind, sev = parse_set(s)
        w = lab != pr
        by[(kind, sev, f)].update(zip(lab[w].tolist(), pr[w].tolist(), strict=True))
    rows = [
        {"noise": k, "severity": sv, "font": f, "true": t, "read": p, "cells": n}
        for (k, sv, f), cnt in sorted(by.items())
        for (t, p), n in sorted(cnt.items())
    ]
    with (RES / "confusions.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    font_names = sorted({f for f in fonts})
    images_per_font = Counter(f for (s, _), f in zip(ids, fonts, strict=True) if s == "clean")
    total_misreads = sum(r["cells"] for r in rows)

    def top(sel, k=10):
        cnt, per_font = Counter(), defaultdict(Counter)
        for r in rows:
            if sel(r):
                cnt[(r["true"], r["read"])] += r["cells"]
                per_font[(r["true"], r["read"])][r["font"]] += r["cells"]
        tot = sum(cnt.values())
        table = []
        for (t, p), n in cnt.most_common(k):
            fonts_txt = ", ".join(f"{f} {c}" for f, c in per_font[(t, p)].most_common())
            table.append([pair(t, p), n, f"{100 * n / tot:.1f}", fonts_txt])
        return tot, table, cnt, per_font

    md = [
        "# CNN confusion pairs on test_final",
        "",
        "Generated by `python scripts/analyse_cells.py` from "
        "`outputs/e2e/cell_logits_test_final.npz` "
        "(argmax = the CNN reading all methods saw; alignment with "
        "`outputs/e2e/e2e_final_noise_cnn.csv` checked by `scripts/check_unweighted.py`). "
        "Full counts per noise type, severity, font and pair: `confusions.csv`. Figure: "
        "`report/figures/fig8_confusions`.",
        "",
        f"Images analysed: {len(ids)} (16 sets x 100, minus 1 where the grid was not found). "
        f"Misread cells: {total_misreads}.",
        "",
        "Fonts: each puzzle index uses the same font in all 16 sets. Puzzles per TEST font: "
        + ", ".join(f"{f} {images_per_font[f]}" for f in font_names)
        + ".",
        "",
    ]
    tot, table, cnt_all, per_font_all = top(lambda r: True)
    md += [
        "## Overall: top 10 (true -> read) pairs",
        "",
        md_table(["pair", "cells", "% of misreads", "cells by font"], table),
        "",
    ]
    font_tot = Counter()
    for r in rows:
        font_tot[r["font"]] += r["cells"]
    md += [
        "## Misread cells by font (all sets)",
        "",
        md_table(
            ["font", "puzzles", "misread cells", "% of misreads"],
            [
                [f, images_per_font[f], font_tot[f], f"{100 * font_tot[f] / tot:.1f}"]
                for f in font_names
            ],
        ),
        "",
    ]
    for kind in NOISE_ORDER:
        sub_tot, sub_table, _, _ = top(lambda r, k=kind: r["noise"] == k)
        label = "clean" if kind == "clean" else f"{kind} (severities 0.25, 0.5, 1.0 pooled)"
        md += [
            f"## {label}: top 10 pairs ({sub_tot} misread cells)",
            "",
            md_table(["pair", "cells", "% of misreads", "cells by font"], sub_table),
            "",
        ]
    (RES / "confusions.md").write_text("\n".join(md), encoding="utf-8")
    return rows, cnt_all, per_font_all, font_names


def fig_confusions(rows, cnt_all, per_font_all, font_names):
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 3.3), gridspec_kw={"width_ratios": [1, 1.25]})
    ax = axes[0]
    top = cnt_all.most_common(10)[::-1]
    y = np.arange(len(top))
    ax.barh(y, [n for _, n in top], left=0.5, color="#4d4d4d", height=0.7)
    for yi, (k, n) in zip(y, top, strict=True):
        by_font = ", ".join(f"{f} {c}" for f, c in per_font_all[k].most_common())
        ax.text((n + 0.5) * 1.25, yi, f"{n}  ({by_font})", va="center", fontsize=6.5, color=INK)
    ax.set_yticks(y)
    ax.set_yticklabels([pair(t, p) for (t, p), _ in top], fontsize=7.5)
    ax.set_xscale("log")
    ax.set_xlabel("misread cells (log scale; fonts in brackets)")
    ax.set_title("Top 10 confusions (true -> read), all sets", loc="left", fontsize=8.5)
    style_axes(ax, ygrid=False)
    ax.set_xlim(0.5, 2e5)

    ax = axes[1]
    sets = sorted(
        {(r["noise"], r["severity"]) for r in rows}, key=lambda k: (NOISE_ORDER.index(k[0]), k[1])
    )
    groups = [((5, 6), "5 -> 6", "#4d4d4d", ""), ((9, 8), "9 -> 8", "white", "////")]
    x = np.arange(len(sets))
    bottom = np.zeros(len(sets))
    for key, lab, face, hatch in groups + [(None, "other pairs", "#bdbdbd", "")]:
        vals = np.array(
            [
                sum(
                    r["cells"]
                    for r in rows
                    if (r["noise"], r["severity"]) == st
                    and (
                        (r["true"], r["read"]) == key
                        if key
                        else (r["true"], r["read"]) not in [g[0] for g in groups]
                    )
                )
                for st in sets
            ],
            float,
        )
        ax.bar(
            x, vals, 0.75, bottom=bottom, color=face, hatch=hatch, edgecolor=INK, lw=0.4, label=lab
        )
        bottom += vals
    ax.set_xticks(x)
    ax.set_xticklabels(
        [
            "clean" if k == "clean" else f"{k.replace('gaussian_noise', 'noise')} {s:g}"
            for k, s in sets
        ],
        rotation=60,
        ha="right",
        fontsize=6.5,
    )
    ax.set_ylabel("misread cells (100 images per set)")
    ax.set_title("Misread cells per test set", loc="left", fontsize=8.5)
    ax.legend(fontsize=7, loc="upper right")
    style_axes(ax)
    fig.tight_layout()
    save(fig, "fig8_confusions")


def noise_flips(ids, labels, pred, fonts, probs):
    idx = {k: i for i, k in enumerate(ids)}
    solved = {
        (r["dataset"], r["image"]): r["correct"] == "True"
        for r in csv.DictReader(MAIN.open(encoding="utf-8"))
        if r["method"] == "maxsat_weighted"
    }
    out = []
    for s in sorted({s for s, _ in ids if s != "clean"}, key=lambda s: parse_set(s)):
        kind, sev = parse_set(s)
        agg = Counter()
        for (ss, im), i in idx.items():
            if ss != s:
                continue
            c = idx[("clean", im)]
            ok_c, ok_n = pred[c] == labels[c], pred[i] == labels[i]
            sm = fonts[i] == "SpaceMono"
            agg["images"] += 1
            agg["clean_wrong"] += int((~ok_c).sum())
            agg["noisy_wrong"] += int((~ok_n).sum())
            agg["wrong_to_right"] += int((~ok_c & ok_n).sum())
            agg["right_to_wrong"] += int((ok_c & ~ok_n).sum())
            agg["wrong_to_right_spacemono"] += int((~ok_c & ok_n).sum()) if sm else 0
            agg["right_to_wrong_spacemono"] += int((ok_c & ~ok_n).sum()) if sm else 0
            agg["wrong_to_other_wrong"] += int((~ok_c & ~ok_n & (pred[c] != pred[i])).sum())
            agg["mw_solved_clean_only"] += solved[("clean", im)] and not solved[(s, im)]
            agg["mw_solved_noisy_only"] += solved[(s, im)] and not solved[("clean", im)]
            agg["images_fewer_misreads"] += int((~ok_n).sum() < (~ok_c).sum())
            agg["images_more_misreads"] += int((~ok_n).sum() > (~ok_c).sum())
            agg["wrong_to_right_was_5to6"] += int(
                (~ok_c & ok_n & (labels[c] == 5) & (pred[c] == 6)).sum()
            )
            if sm:
                five = labels[c] == 5
                agg["sm5_cells"] += int(five.sum())
                agg["sm5_right_clean"] += int((five & ok_c).sum())
                agg["sm5_right_noisy"] += int((five & ok_n).sum())
                agg["_p5_clean"] += float(probs[c][five, 5].sum())
                agg["_p5_noisy"] += float(probs[i][five, 5].sum())
        agg["net_change"] = agg["noisy_wrong"] - agg["clean_wrong"]
        agg["sm5_mean_p5_clean"] = round(agg.pop("_p5_clean") / agg["sm5_cells"], 4)
        agg["sm5_mean_p5_noisy"] = round(agg.pop("_p5_noisy") / agg["sm5_cells"], 4)
        out.append({"noise": kind, "severity": sev, **agg})
    with (RES / "noise_flips.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    cols = [
        ("noise", "noise"),
        ("severity", "severity"),
        ("images", "images"),
        ("clean_wrong", "misread cells, clean"),
        ("noisy_wrong", "misread cells, noisy"),
        ("wrong_to_right", "wrong -> right"),
        ("right_to_wrong", "right -> wrong"),
        ("wrong_to_other_wrong", "wrong -> other wrong"),
        ("net_change", "net change"),
        ("wrong_to_right_spacemono", "wrong -> right (SpaceMono)"),
        ("right_to_wrong_spacemono", "right -> wrong (SpaceMono)"),
        ("images_fewer_misreads", "images with fewer misreads"),
        ("images_more_misreads", "images with more misreads"),
        ("wrong_to_right_was_5to6", "wrong -> right that were 5 -> 6 in clean"),
        ("sm5_cells", "SpaceMono true-5 cells"),
        ("sm5_right_clean", "...read right, clean"),
        ("sm5_right_noisy", "...read right, noisy"),
        ("sm5_mean_p5_clean", "...mean p(5), clean"),
        ("sm5_mean_p5_noisy", "...mean p(5), noisy"),
        ("mw_solved_noisy_only", "maxsat_weighted solved noisy only"),
        ("mw_solved_clean_only", "maxsat_weighted solved clean only"),
    ]
    md = [
        "# Noisy vs clean renders of the same puzzles",
        "",
        "Generated by `python scripts/analyse_cells.py` (data: `noise_flips.csv`). "
        "Each noisy image "
        "is compared with the clean render of the same puzzle index (same puzzle, same font, same "
        "layout; only the noise differs). Cell counts are over all 81 cells, using the CNN argmax. "
        "*wrong -> right*: misread in the clean render, read correctly in the noisy one; *right -> "
        "wrong*: the reverse; *wrong -> other wrong*: misread in both, as different digits. The "
        "last two columns compare maxsat_weighted's full-grid outcome on the pair "
        "(`outputs/e2e/e2e_final_noise_cnn.csv`). rotate 1.0 has 99 images (one grid not found).",
        "",
        md_table([h for _, h in cols], [[r[k] for k, _ in cols] for r in out]),
        "",
    ]
    (RES / "noise_flips.md").write_text("\n".join(md), encoding="utf-8")
    return out


def main() -> None:
    ids, labels, pred, fonts, probs = load()
    rows, cnt_all, per_font_all, font_names = confusions(ids, labels, pred, fonts)
    fig_confusions(rows, cnt_all, per_font_all, font_names)
    noise_flips(ids, labels, pred, fonts, probs)
    print("wrote report/results/confusions.{csv,md}, noise_flips.{csv,md}, fig8_confusions")


if __name__ == "__main__":
    main()
